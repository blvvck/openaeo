import { motion } from 'framer-motion';
import { format } from 'date-fns';
import { APP_CONFIG } from '@/config/app';
import {
  FileText,
  Calendar,
  AlertTriangle,
  Clock,
  TrendingUp,
  TrendingDown,
  Minus,
} from 'lucide-react';
import { cn } from '@/lib/utils';
import { fadeIn, staggerContainer, staggerItem } from '@/lib/motion';
import { Badge } from '@/components/ui/badge';
import {
  Card,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from '@/components/ui/card';
import { Separator } from '@/components/ui/divider';
import { CardSkeleton } from '@/components/shared/skeleton-loader';
import { EmptyState } from '@/components/shared/empty-state';
import { usePublicReport } from './useReports';
import { REPORT_SECTIONS, type ReportSection, type PublicReportData } from './types';

interface PublicReportViewProps {
  /** Public report ID from URL */
  publicId: string;
  /** Additional classes */
  className?: string;
}

/**
 * PublicReportView - Display a publicly shared report
 *
 * Features:
 * - Fetches report data via public API
 * - Displays all included sections
 * - Branded header with date range
 * - Error handling for expired/revoked links
 */
export function PublicReportView({
  publicId,
  className,
}: PublicReportViewProps) {
  const { data: report, isLoading, error } = usePublicReport(publicId);

  if (isLoading) {
    return (
      <div className={cn('space-y-6', className)}>
        <CardSkeleton hasHeader contentLines={2} />
        <div className="grid gap-6 md:grid-cols-2">
          <CardSkeleton hasHeader contentLines={4} />
          <CardSkeleton hasHeader contentLines={4} />
        </div>
        <CardSkeleton hasHeader contentLines={6} />
      </div>
    );
  }

  if (error) {
    const isExpired = error.message.includes('expired');
    const isNotFound = error.message.includes('not found');

    return (
      <div
        className={cn(
          'flex items-center justify-center min-h-[400px]',
          className
        )}
      >
        <EmptyState
          icon={AlertTriangle}
          title={
            isExpired
              ? 'Report Expired'
              : isNotFound
              ? 'Report Not Found'
              : 'Error Loading Report'
          }
          description={
            isExpired
              ? 'This shared report link has expired. Please request a new link from the report owner.'
              : isNotFound
              ? 'This report does not exist or has been revoked.'
              : 'There was an error loading this report. Please try again later.'
          }
        />
      </div>
    );
  }

  if (!report) {
    return null;
  }

  return (
    <motion.div
      variants={staggerContainer}
      initial="hidden"
      animate="visible"
      className={cn('space-y-6', className)}
    >
      {/* Report Header */}
      <motion.div variants={staggerItem}>
        <Card>
          <CardHeader>
            <div className="flex items-start justify-between">
              <div className="space-y-1">
                <CardTitle className="flex items-center gap-2 text-2xl">
                  <FileText className="w-6 h-6" />
                  {report.title}
                </CardTitle>
                <CardDescription className="flex items-center gap-4">
                  <span className="flex items-center gap-1">
                    <Calendar className="w-4 h-4" />
                    {format(new Date(report.dateRange.start), 'MMM d, yyyy')} -{' '}
                    {format(new Date(report.dateRange.end), 'MMM d, yyyy')}
                  </span>
                  <span className="flex items-center gap-1">
                    <Clock className="w-4 h-4" />
                    Generated{' '}
                    {format(new Date(report.generatedAt), 'MMM d, yyyy h:mm a')}
                  </span>
                </CardDescription>
              </div>
              <Badge variant="secondary">{report.brandName}</Badge>
            </div>
          </CardHeader>
        </Card>
      </motion.div>

      {/* Report Sections */}
      {Object.entries(report.sections).map(([sectionKey, sectionData]) => {
        const section = sectionKey as ReportSection;
        const sectionInfo = REPORT_SECTIONS[section];

        if (!sectionData || !sectionInfo) return null;

        return (
          <motion.div key={section} variants={staggerItem}>
            <ReportSectionCard
              section={section}
              title={sectionInfo.label}
              data={sectionData}
            />
          </motion.div>
        );
      })}

      {/* Footer */}
      <motion.div variants={staggerItem}>
        <Separator className="my-8" />
        <p className="text-center text-sm text-muted-foreground">
          This report was generated by {APP_CONFIG.fullName}. Data is based on
          analysis from{' '}
          {format(new Date(report.dateRange.start), 'MMMM d')} to{' '}
          {format(new Date(report.dateRange.end), 'MMMM d, yyyy')}.
        </p>
      </motion.div>
    </motion.div>
  );
}

// ===== Report Section Card =====

interface ReportSectionCardProps {
  section: ReportSection;
  title: string;
  data: unknown;
}

function ReportSectionCard({ section, title, data }: ReportSectionCardProps) {
  // Render different content based on section type
  const renderContent = () => {
    switch (section) {
      case 'executive_summary':
        return <ExecutiveSummaryContent data={data as ExecutiveSummaryData} />;
      case 'visibility_metrics':
        return <VisibilityMetricsContent data={data as VisibilityMetricsData} />;
      case 'platform_breakdown':
        return <PlatformBreakdownContent data={data as PlatformBreakdownData} />;
      case 'competitor_analysis':
        return <CompetitorAnalysisContent data={data as CompetitorAnalysisData} />;
      default:
        return <GenericSectionContent data={data} />;
    }
  };

  return (
    <Card>
      <CardHeader>
        <CardTitle className="text-lg">{title}</CardTitle>
      </CardHeader>
      <CardContent>{renderContent()}</CardContent>
    </Card>
  );
}

// ===== Section Content Components =====

interface ExecutiveSummaryData {
  visibilityScore: number;
  visibilityChange: number;
  totalMentions: number;
  mentionChange: number;
  topPlatform: string;
  keyInsights: string[];
}

function ExecutiveSummaryContent({ data }: { data: ExecutiveSummaryData }) {
  return (
    <div className="space-y-6">
      <div className="grid gap-4 md:grid-cols-3">
        <MetricCard
          label="Visibility score"
          value={data.visibilityScore}
          change={data.visibilityChange}
          suffix="/100"
        />
        <MetricCard
          label="Total mentions"
          value={data.totalMentions}
          change={data.mentionChange}
        />
        <MetricCard
          label="Top platform"
          value={data.topPlatform}
          isText
        />
      </div>

      {data.keyInsights && data.keyInsights.length > 0 && (
        <div>
          <h4 className="text-sm font-medium mb-2">Key insights</h4>
          <ul className="space-y-2">
            {data.keyInsights.map((insight, idx) => (
              <li key={idx} className="text-sm text-muted-foreground flex gap-2">
                <span className="text-primary">-</span>
                {insight}
              </li>
            ))}
          </ul>
        </div>
      )}
    </div>
  );
}

interface VisibilityMetricsData {
  currentScore: number;
  previousScore: number;
  change: number;
  trend: Array<{ date: string; score: number }>;
}

function VisibilityMetricsContent({ data }: { data: VisibilityMetricsData }) {
  return (
    <div className="space-y-4">
      <div className="flex items-center gap-6">
        <div className="text-4xl font-bold">{data.currentScore}</div>
        <TrendIndicator value={data.change} />
      </div>
      <p className="text-sm text-muted-foreground">
        Previous period: {data.previousScore}
      </p>

      {data.trend && data.trend.length > 0 && (
        <div className="h-32 mt-4 flex items-end gap-1">
          {data.trend.map((point, idx) => (
            <div
              key={idx}
              className="flex-1 bg-primary/20 rounded-t"
              style={{ height: `${point.score}%` }}
              title={`${format(new Date(point.date), 'MMM d')}: ${point.score}`}
            />
          ))}
        </div>
      )}
    </div>
  );
}

interface PlatformBreakdownData {
  platforms: Array<{
    name: string;
    score: number;
    mentions: number;
  }>;
}

function PlatformBreakdownContent({ data }: { data: PlatformBreakdownData }) {
  return (
    <div className="space-y-4">
      {data.platforms.map((platform) => (
        <div key={platform.name} className="space-y-1">
          <div className="flex justify-between text-sm">
            <span className="font-medium">{platform.name}</span>
            <span className="text-muted-foreground">
              {platform.score}/100 ({platform.mentions} mentions)
            </span>
          </div>
          <div className="h-2 bg-muted rounded-full overflow-hidden">
            <div
              className="h-full bg-primary rounded-full"
              style={{ width: `${platform.score}%` }}
            />
          </div>
        </div>
      ))}
    </div>
  );
}

interface CompetitorAnalysisData {
  competitors: Array<{
    name: string;
    mentions: number;
    sentiment: number;
    change: number;
  }>;
}

function CompetitorAnalysisContent({ data }: { data: CompetitorAnalysisData }) {
  return (
    <div className="space-y-3">
      {data.competitors.map((competitor, idx) => (
        <div
          key={competitor.name}
          className={cn(
            'flex items-center justify-between p-3 rounded-lg',
            idx === 0 ? 'bg-primary/10' : 'bg-muted/50'
          )}
        >
          <div className="flex items-center gap-3">
            <span className="text-lg font-bold text-muted-foreground">
              #{idx + 1}
            </span>
            <div>
              <p className="font-medium">{competitor.name}</p>
              <p className="text-sm text-muted-foreground">
                {competitor.mentions} mentions
              </p>
            </div>
          </div>
          <TrendIndicator value={competitor.change} />
        </div>
      ))}
    </div>
  );
}

function GenericSectionContent({ data }: { data: unknown }) {
  if (typeof data === 'string') {
    return <p className="text-muted-foreground">{data}</p>;
  }

  if (Array.isArray(data)) {
    return (
      <ul className="space-y-2">
        {data.map((item, idx) => (
          <li key={idx} className="text-sm text-muted-foreground">
            {typeof item === 'string' ? item : JSON.stringify(item)}
          </li>
        ))}
      </ul>
    );
  }

  return (
    <pre className="text-sm text-muted-foreground overflow-auto">
      {JSON.stringify(data, null, 2)}
    </pre>
  );
}

// ===== Helper Components =====

function MetricCard({
  label,
  value,
  change,
  suffix = '',
  isText = false,
}: {
  label: string;
  value: number | string;
  change?: number;
  suffix?: string;
  isText?: boolean;
}) {
  return (
    <div className="p-4 rounded-lg bg-muted/50">
      <p className="text-sm text-muted-foreground">{label}</p>
      <div className="flex items-baseline gap-2 mt-1">
        <span className={cn('font-bold', isText ? 'text-lg' : 'text-2xl')}>
          {value}
          {suffix}
        </span>
        {typeof change === 'number' && <TrendIndicator value={change} size="sm" />}
      </div>
    </div>
  );
}

function TrendIndicator({
  value,
  size = 'default',
}: {
  value: number;
  size?: 'sm' | 'default';
}) {
  const isPositive = value > 0;
  const isNegative = value < 0;
  const isNeutral = value === 0;

  const iconSize = size === 'sm' ? 'w-3 h-3' : 'w-4 h-4';
  const textSize = size === 'sm' ? 'text-xs' : 'text-sm';

  return (
    <span
      className={cn(
        'flex items-center gap-1',
        textSize,
        isPositive && 'text-green-500',
        isNegative && 'text-red-500',
        isNeutral && 'text-muted-foreground'
      )}
    >
      {isPositive && <TrendingUp className={iconSize} />}
      {isNegative && <TrendingDown className={iconSize} />}
      {isNeutral && <Minus className={iconSize} />}
      {isPositive && '+'}
      {value}%
    </span>
  );
}
